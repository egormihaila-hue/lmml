from difflib import get_close_matches
import re
import unicodedata
import pandas as pd

# Загружаем исходную таблицу с маршрутами из CSV-файла
df = pd.read_csv('routes.csv')


def normalize_town(s):
  # Превращаем значение в строку и обрезаем пробелы/переносы по краям
  s = str(s).strip()
  # Расщепляем скандинавские/диакритические символы (ä -> a + ¨) и оставляем только чистую латиницу (ASCII)
  s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode('ascii')
  # Удаляем лишние знаки препинания (точки, дефисы, кавычки) в самом начале и конце строки
  s = re.sub(r'^[\W_]+|[\W_]+$', '', s)
  # Заменяем любые двойные или тройные пробелы внутри названия на один обычный пробел
  s = re.sub(r'\s+', ' ', s)
  # Делаем первую букву каждого слова заглавной, а остальные строчными ('HELSINKI' -> 'Helsinki')
  return s.title()


# Применяем базовую очистку ко всем значениям в столбцах отправления и прибытия
df['from_town'] = df['from_town'].apply(normalize_town)
df['to_town'] = df['to_town'].apply(normalize_town)

# Собираем все уникальные названия городов из обоих столбцов и сортируем по алфавиту
towns = sorted(set(df['from_town']).union(set(df['to_town'])))

# Считаем, сколько раз каждый город встречается в таблице (чтобы отличить правильное имя от редкой опечатки)
counts = pd.concat([df['from_town'], df['to_town']]).value_counts().to_dict()

# Сортируем уникальные города от самых частых (эталонов) к самым редким (опечаткам)
towns_by_freq = sorted(towns, key=lambda x: (-counts[x], x))

groups = []  # Сюда будем складывать итоговые группы городов
visited = set()  # Сюда записываем города, которые уже попали в какую-либо группу

# Проходим по всем городам от популярных к редким
for t in towns_by_freq:
  # Если город уже добавлен в одну из прошлых групп (как чья-то опечатка) — пропускаем его
  if t in visited:
    continue

  # Ищем все названия, похожие на текущий город минимум на 78% (ловит опечатки в 1-2 буквах)
  similar = get_close_matches(t, towns_by_freq, n=10, cutoff=0.78)

  # Оставляем только ещё не распределённые варианты и сортируем их по убыванию частоты
  # Благодаря этому самый частый (правильный) вариант всегда стоит первым под индексом [0]
  group = sorted(
      [s for s in similar if s not in visited], key=lambda x: (-counts[x], x)
  )

  # Помечаем все слова из этой группы как обработанные
  visited.update(group)
  # Сохраняем готовую группу в общий список
  groups.append(group)

# Сортируем итоговый список групп по алфавиту, ориентируясь на главный город группы g[0]
groups.sort(key=lambda g: g[0])

# Выводим количество получившихся групп и сравниваем с целью задачи (116)
print(f'Grouped towns count: {len(groups)} (target: 116)\n')

# Выводим пронумерованный список только главных (очищенных) названий городов
for i, g in enumerate(groups, 1):
  print(f'{i:3d}. {g[0]}')
